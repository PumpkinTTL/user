export const contactOrder: string[] = ['telegram', 'whatsapp', 'x', 'wechat', 'qq']

export interface ContactItem {
  key: string
  value: string
  label: string
  path: string
  viewBox: string
  color: string
  isLink: boolean
}

export function getContactList(contact: Record<string, unknown> | null | undefined): ContactItem[] {
  if (!contact) return []
  return contactOrder
    .map((key) => {
      const raw = contact[key]
      const value = typeof raw === 'string' ? raw.trim() : ''
      if (!value) return null
      const icon = contactIcons[key]
      if (!icon) return null
      return {
        key,
        value,
        ...icon,
        isLink: /^https?:\/\//i.test(value),
      }
    })
    .filter((item): item is ContactItem => item !== null)
}
